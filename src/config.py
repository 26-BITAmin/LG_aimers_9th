# ── 시즌 진행분 축 (MODEL.md §7.55 투수 · §7.57 타자 · src/asofdelta.py) ──
# `asof_*`가 커리어 누적이라 "이 엔티티의 **올해** 값"이 모델에 들어간 적이 없다.
