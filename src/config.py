#
# gap_success   투수의 올해 성공률 − 커리어
#   잔차 t +16.05 / +8.02 (대조군 −0.68 / +0.12)   고원 폭 10배
#   **LB 997.89 → 1024.03 (+26.14), 배율 0.93 — 홀드아웃이 그대로 왔다**
#
# gap_bsuccess  타자가 올해 상대해온 제구 수준 − 커리어
#   증분 잔차 t +12.43 / +6.53 — `gap_success`를 얹은 뒤에도 6.70 → 6.53으로만 준다
#   = **거의 직교**. 다른 엔티티이기 때문이다.
#   증분 β 스윕 f2023 +47.97 / f2024 +16.54, 고원 [0.005, 0.03] 폭 6배,
#   **크기비 2.90 — 이 계열에서 처음으로 조건 ③(3배 이내)을 통과한다.**
#   대조군(ID 재배정)은 어떤 β에서도 양수가 없다 (최선 −3.72).
#
# ⛔ β는 CV 최댓값이 아니다. §7.37 규칙 — **±50% 전이 오차 밴드가 통째로 통과
#    구간 안에 들어오는 값**을 고른다 (가장자리를 밟지 않는다).
#      gap_success   고원 [0.005, 0.05] → 허용 [0.010, 0.033] → 0.02
#      gap_bsuccess  고원 [0.005, 0.03] → 허용 [0.010, 0.020] → 0.015
#      (0.02는 밴드 상단이 정확히 고원 경계 0.03을 밟는다. CV 비용은 −1.6뿐)
#
# ⛔ **LB로 β를 다시 고르지 않는다** (SUBMISSIONS.md 규칙 2).
#    실현 이득이 작다는 것은 cov가 작다는 뜻이고 그러면 최적 β는 **낮아진다**.
#
