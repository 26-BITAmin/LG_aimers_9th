# ── 투수별 플래툰 편차 (`src/ctxfit.py`, MODEL.md §7.36) ─────
# δ(투수, 타자손잡이) = 수축((그 손잡이 상대 성공률) − (그 투수 전체 성공률))
# 최종 로짓에 β·δ를 더한다. **피처가 아니라 사후 보정항**이라 재학습이 없다.
#
# 왜 이 축이었나: 투수×타자손잡이 천장 1127.9 vs 투수 단독 838.8 (§7.34 G).
# `asof_*`에는 손잡이별 분할이 없어서 이 정보가 모델에 들어간 적이 없다.
#
# 2 fold 실측 (β 스윕, 배포와 같은 블렌드 로짓 위에서):
#   β      0.50   1.00   1.25   1.50   2.00   2.50   3.00   4.00
#   f2023 +11.31 +18.65 +20.84 +22.04 +21.49 +17.00  +8.59 -19.92
#   f2024  +9.81 +16.49 +18.65 +20.03 +20.46 +17.77 +11.99  -8.82
#   → β 0.25~3.0 **전 구간**에서 양 fold 양수, 크기비 1.05~1.40 (조건 ②③ 통과)
#
# β=1.5를 고른 이유는 최댓값이어서가 아니라 **하방이 비대칭**이기 때문이다.
# 2025에서 전이 강도가 절반이면 β=1.5는 실효 0.75(+14)로 내려앉을 뿐이지만,
# β=2.5를 골랐다가 전이가 1.5배면 실효 3.75(음수)로 떨어진다.
#
# 대조군: 리그 평균 플래툰(투수별 아님)은 f2023 −6.73 / f2024 +0.10 —
# 손잡이 **주효과는 모델이 이미 쓰고 있고** 투수별 편차만 안 쓰고 있었다.
# ── 사후 로짓 보정 축 (features.CTX_CODERS · src/ctxfit.py) ─────────────
# 순서는 로짓 덧셈이라 무관하다. β=0인 축은 fit 자체를 건너뛴다.
#
# count4 (MODEL.md §7.37) — 배포 상태(블렌드 + 1.5·δ_hand) **위의 증분**으로 쟀다.
#   잔차 t  +4.6 / +5.7      쌍체 t  3.1 / 4.3
#   BSS     +7.49 / +9.74    크기비 1.30      대조군(리그평균 카운트) −0.20 / −5.28
#
# β=1.0은 최댓값이 아니다. Δ 최댓값은 β=1.5(+8.52/+12.11)인데 거기서 쌍체 t가
# 2.3으로 조건 ①의 경계에 붙는다 — SE가 β에 비례해 커지기 때문이다.
# 조건 ①②③ 통과 구간이 β ∈ [0.25, 1.5]인데, **β=1.0이면 ±50% 전이 오차 밴드
# [0.5, 1.5]가 통째로 통과 구간 안에 들어온다.** 1.5를 고르면 전이가 1.5배만 돼도
# 실효 2.25로 구간 밖이다. 가장자리를 밟지 않는 것이 선택 기준이다.
#
